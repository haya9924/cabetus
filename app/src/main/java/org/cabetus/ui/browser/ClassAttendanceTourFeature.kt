package org.cabetus.ui.browser

/**
 * 出欠一覧の前景自動巡回（[ClassAttendanceTourRunner]）を公開するかどうかの唯一のスイッチ。
 *
 * この巡回は**未完成・実機未検証**のため、既定では完全に無効にする。
 * 無効の間は、画面側で巡回の開始ボタン・進捗・中止ボタン・結果ダイアログを一切出さず、
 * [ClassAttendanceTourRunner] も生成しない（[ClassAttendanceTourViewModel.start] を呼ばない）。
 * これにより、実機で想定外の DOM に出会った場合でも、
 * 「一覧リンクのクリック → 詳細の読み取り → 戻る」を自動で繰り返す危険な操作は発生しない。
 *
 * 他の時間割取り込み・出欠詳細の単科プレビューはこのフラグの対象外で、従来どおり利用できる。
 *
 * 有効化するのは、実機で
 * - 一覧の件数・並び・リンク先が巡回中に変わらないこと
 * - 詳細 DOM が実際に切り替わってから読み取れること
 * - 「戻る」で一覧に戻れること
 * - 中止・画面破棄で即座に停止できること
 * を確認できた後に行う。有効化する場合はこの定数を変更し、
 * [InAppBrowserScreen] 側の表示・入力遮断のガードも合わせて確認する。
 */
object ClassAttendanceTourFeature {

    /** 既定値。危険な巡回開始 UI を出さないため、リリースでは常に false。 */
    const val ENABLED: Boolean = false

    /** 画面に出す未完成の表示。 */
    const val INCOMPLETE_LABEL: String = "未完成・実機未検証"

    /**
     * 無効時に画面へ出す理由。巡回が「読み取り専用」であっても、
     * 一覧の行リンクを自動で開く操作自体が未検証であることを明示する。
     */
    const val DISABLED_REASON: String =
        "出欠一覧の自動巡回は未完成で、実機での動作確認ができていません。" +
            "一覧の科目リンクを自動で開く操作を誤って繰り返さないよう、" +
            "既定では開始ボタンを表示せず完全に無効にしています。" +
            "表示中の1科目の出欠を読み取るプレビューは、これまでどおり利用できます。"

    /** 巡回開始 UI を出してよいか。 */
    fun available(): Boolean = ENABLED
}
